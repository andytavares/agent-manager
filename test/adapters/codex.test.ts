import { beforeEach, expect, test } from "bun:test"
import { appendFileSync, cpSync, mkdirSync, mkdtempSync, realpathSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { codex } from "../../src/adapters/codex"
import type { Item, Kind, Roots } from "../../src/core/model"

const fixtures = join(import.meta.dir, "../fixtures/codex")
let base: string
let home: string
let codexHome: string
let project: string
let roots: Roots

// Copy the fixtures so each test can add a .git marker and edit config without touching the repo.
beforeEach(() => {
  base = realpathSync(mkdtempSync(join(tmpdir(), "codex-adapter-")))
  cpSync(fixtures, base, { recursive: true })
  home = join(base, "home")
  codexHome = join(home, ".codex")
  project = join(base, "project")
  mkdirSync(join(project, ".git"))
  roots = { home, project: join(project, "sub"), env: { CODEX_SYSTEM_SKILLS: join(base, "system-skills") } }
})

function trustProject() {
  appendFileSync(join(codexHome, "config.toml"), `\n[projects."${project}"]\ntrust_level = "trusted"\n`)
}

async function byName(kind: Kind, r: Roots = roots): Promise<Record<string, Item>> {
  return Object.fromEntries((await codex.list(kind, r)).map((item) => [item.name, item]))
}

async function globalMemory(): Promise<Record<string, Item>> {
  const items = (await codex.list("memory", roots)).filter((item) => item.path.startsWith(codexHome))
  return Object.fromEntries(items.map((item) => [item.name, item]))
}

test("detect is true only when the Codex home exists", async () => {
  expect(await codex.detect(roots)).toBe(true)
  expect(await codex.detect({ ...roots, home: join(base, "nowhere") })).toBe(false)
})

test("CODEX_HOME overrides ~/.codex", async () => {
  const r = { ...roots, home: join(base, "nowhere"), env: { ...roots.env, CODEX_HOME: codexHome } }
  expect(await codex.detect(r)).toBe(true)
  expect((await byName("mcp", r)).linear?.path).toBe(join(codexHome, "config.toml"))
})

test("a non-empty AGENTS.override.md shadows the global AGENTS.md", async () => {
  const items = await globalMemory()
  expect(items["AGENTS.override.md"]).toMatchObject({ scope: "global", loadedBy: ["codex"] })
  expect(items["AGENTS.md"]).toMatchObject({ loadedBy: [], warnings: ["shadowed by AGENTS.override.md"] })
})

test("without an override the global AGENTS.md is loaded", async () => {
  writeFileSync(join(codexHome, "AGENTS.override.md"), "  \n")
  const items = await globalMemory()
  expect(items["AGENTS.md"]).toMatchObject({ loadedBy: ["codex"] })
  expect(items["AGENTS.md"]?.warnings).toBeUndefined()
})

test("project memory walks from the git root down, skipping empty files and using fallback names", async () => {
  const project_ = (await codex.list("memory", roots)).filter((item) => item.scope === "project")
  expect(project_.map((item) => item.path)).toEqual([join(project, "AGENTS.md"), join(project, "sub", "TEAM.md")])
  expect(await codex.read(project_[1]!)).toEqual({ type: "text", text: "Sub fallback memory\n" })
})

test("without a git root only the project dir is read", async () => {
  const r = { ...roots, project: join(base, "home") }
  writeFileSync(join(home, "AGENTS.md"), "Home dir memory\n")
  const project_ = (await codex.list("memory", r)).filter((item) => item.scope === "project")
  expect(project_.map((item) => item.path)).toEqual([join(home, "AGENTS.md")])
})

test("generated memories are listed recursively, read and delete only, on when the feature is on", async () => {
  const items = await byName("memory")
  const memory = items["topics/tools.md"]!
  expect(memory).toMatchObject({ scope: "global", warnings: ["generated by Codex: read and delete only"] })
  expect(memory.offIn).toBeUndefined()
  expect(items["summary.md"]?.path).toBe(join(codexHome, "memories_v2", "summary.md"))
})

test("generated memories are off in Codex when the memories feature is not on", async () => {
  writeFileSync(join(codexHome, "config.toml"), "# memories feature missing\n")
  expect((await byName("memory"))["topics/tools.md"]?.offIn).toEqual(["codex"])
})

test("global MCP servers map url, bearer token and headers; extra keys go to native", async () => {
  const items = await byName("mcp")
  expect(items.linear).toMatchObject({ scope: "global", key: "mcp_servers.linear", loadedBy: ["codex"] })
  expect(await codex.read(items.linear!)).toEqual({
    type: "mcp",
    server: {
      name: "linear",
      transport: "http",
      enabled: true,
      url: "https://mcp.linear.app/mcp",
      headers: { "X-Team": "core", Authorization: "Bearer ${LINEAR_TOKEN}" },
      native: { bearer_token_env_var: "LINEAR_TOKEN", startup_timeout_sec: 20 },
    },
  })
})

test("an MCP server with enabled = false is off in Codex and reads as stdio", async () => {
  const items = await byName("mcp")
  expect(items.files?.offIn).toEqual(["codex"])
  expect(items.files?.loadedBy).toEqual([]) // an off harness is not in loadedBy
  expect(await codex.read(items.files!)).toEqual({
    type: "mcp",
    server: { name: "files", transport: "stdio", enabled: false, command: "npx", args: ["-y", "server-files"], env: { ROOT: "/tmp" }, native: {} },
  })
})

test("project MCP servers are on when the project is trusted", async () => {
  trustProject()
  const repo = (await byName("mcp")).repo!
  expect(repo).toMatchObject({ scope: "project", path: join(project, ".codex", "config.toml"), key: "mcp_servers.repo" })
  expect(repo.offIn).toBeUndefined()
})

test("project MCP servers are off with a warning when the project is not trusted", async () => {
  expect((await byName("mcp")).repo).toMatchObject({ offIn: ["codex"], warnings: ["project not trusted in Codex"] })
})

test("malformed TOML gives no items and no crash", async () => {
  writeFileSync(join(codexHome, "config.toml"), "[mcp_servers.broken\ncommand = \n")
  expect((await codex.list("mcp", roots)).filter((item) => item.scope === "global")).toEqual([])
  expect((await byName("memory"))["AGENTS.override.md"]).toBeDefined()
})

test("skills come from ~/.agents/skills, system skills, the Codex home and project dirs", async () => {
  const items = await byName("skill")
  expect(items.research).toMatchObject({ scope: "global", path: join(home, ".agents/skills/research"), loadedBy: ["codex"] })
  expect(items.research?.offIn).toBeUndefined()
  expect(items.plan).toMatchObject({ scope: "global", readOnly: "system skills" })
  expect(items["old-skill"]).toMatchObject({ loadedBy: ["codex"], warnings: ["* likely not loaded: move to ~/.agents/skills"] })
  expect(items["local-skill"]?.scope).toBe("project")
  expect(items["root-skill"]?.scope).toBe("project")
  expect(await codex.read(items.research!)).toEqual({ type: "text", text: "---\nname: research\n---\nResearch\n" })
})

test("a skill disabled in [[skills.config]] is off in Codex", async () => {
  expect((await byName("skill")).pdf?.offIn).toEqual(["codex"])
})

test("a skill can be disabled by path", async () => {
  appendFileSync(join(codexHome, "config.toml"), `\n[[skills.config]]\npath = "${join(project, ".agents/skills/root-skill/SKILL.md")}"\nenabled = false\n`)
  expect((await byName("skill"))["root-skill"]?.offIn).toEqual(["codex"])
})

test("installed plugins take the highest version; enabled comes from config", async () => {
  const items = await byName("plugin")
  expect(items["github@official"]).toMatchObject({ path: join(codexHome, "plugins/cache/official/github/1.10.0"), loadedBy: ["codex"] })
  expect(items["github@official"]?.offIn).toBeUndefined()
  expect(items["linear@official"]?.offIn).toEqual(["codex"])
  expect(await codex.read(items["github@official"]!)).toEqual({
    type: "plugin",
    plugin: { name: "github@official", enabled: true, version: "1.10.0", source: "official" },
  })
})

test("trusted project config wins for plugin enabled", async () => {
  trustProject()
  expect((await byName("plugin"))["github@official"]?.offIn).toEqual(["codex"])
})

test("plugins named only in config are listed as not installed", async () => {
  const slack = (await byName("plugin"))["slack@official"]!
  expect(slack).toMatchObject({ path: join(codexHome, "config.toml"), loadedBy: [], warnings: ["not installed"] })
  expect(await codex.read(slack)).toEqual({ type: "plugin", plugin: { name: "slack@official", enabled: true, source: "official" } })
})
