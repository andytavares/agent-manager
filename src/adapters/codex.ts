import { existsSync, readFileSync } from "node:fs"
import { readdir } from "node:fs/promises"
import { basename, dirname, join, relative } from "node:path"
import { parse, patch, stringify } from "@decimalturn/toml-patch"
import type { Change, HarnessAdapter, Item, ItemDetail, Kind, McpServer, Roots, Scope, WritePlan } from "../core/model"
import { emptyPlan, planMemoryFile } from "../core/memory-plan"
import { listSkillFolders } from "../core/skills"

type Table = Record<string, any>

const GENERATED_WARNING = "generated by Codex: read and delete only"
const MEMORY_FILES: Partial<Record<Scope, string[]>> = {
  global: ["AGENTS.md", "AGENTS.override.md"],
  project: ["AGENTS.md", "AGENTS.override.md"],
}

interface Context {
  home: string
  codexHome: string
  globalPath: string
  global: Table
  dirs: string[] // project root down to roots.project
  projectPath: string
  project: Table
  trusted: boolean
}

// A missing or malformed file reads as an empty table, so it gives no items.
function readToml(path: string): Table {
  try {
    return existsSync(path) ? (parse(readFileSync(path, "utf8")) as Table) : {}
  } catch {
    return {}
  }
}

function projectDirs(project: string): string[] {
  const dirs: string[] = []
  for (let dir = project; ; dir = dirname(dir)) {
    dirs.unshift(dir)
    if (existsSync(join(dir, ".git"))) return dirs
    if (dirname(dir) === dir) return [project]
  }
}

function context(roots: Roots): Context {
  const codexHome = roots.env.CODEX_HOME ?? join(roots.home, ".codex")
  const globalPath = join(codexHome, "config.toml")
  const global = readToml(globalPath)
  const dirs = projectDirs(roots.project)
  const projectPath = join(dirs[0]!, ".codex", "config.toml")
  const trusted = global.projects?.[dirs[0]!]?.trust_level === "trusted"
  return { home: roots.home, codexHome, globalPath, global, dirs, projectPath, project: readToml(projectPath), trusted }
}

function item(fields: Omit<Item, "harness" | "loadedBy"> & { loadedBy?: Item["loadedBy"] }): Item {
  const loadedBy: Item["loadedBy"] = fields.offIn?.includes("codex") ? [] : ["codex"]
  const result: Item = { harness: "codex", loadedBy, ...fields }
  for (const key of ["offIn", "warnings", "readOnly"] as const) if (result[key] === undefined) delete result[key]
  return result
}

const off = (disabled: boolean) => (disabled ? (["codex"] as Item["offIn"]) : undefined)

function hasText(path: string): boolean {
  return existsSync(path) && readFileSync(path, "utf8").trim() !== ""
}

function globalMemory(ctx: Context): Item[] {
  const override = join(ctx.codexHome, "AGENTS.override.md")
  const agents = join(ctx.codexHome, "AGENTS.md")
  const overrideLoaded = hasText(override)
  const items: Item[] = []
  if (existsSync(override)) items.push(item({ kind: "memory", scope: "global", name: "AGENTS.override.md", path: override, loadedBy: overrideLoaded ? ["codex"] : [] }))
  if (existsSync(agents)) {
    const warnings = overrideLoaded ? ["shadowed by AGENTS.override.md"] : undefined
    items.push(item({ kind: "memory", scope: "global", name: "AGENTS.md", path: agents, loadedBy: overrideLoaded ? [] : ["codex"], warnings }))
  }
  return items
}

function projectMemory(ctx: Context): Item[] {
  const fallbacks: string[] = Array.isArray(ctx.global.project_doc_fallback_filenames) ? ctx.global.project_doc_fallback_filenames : []
  const names = ["AGENTS.override.md", "AGENTS.md", ...fallbacks]
  return ctx.dirs.flatMap((dir) => {
    const path = names.map((name) => join(dir, name)).find(hasText)
    return path ? [item({ kind: "memory", scope: "project", name: relative(ctx.dirs[0]!, path), path })] : []
  })
}

async function generatedMemory(ctx: Context): Promise<Item[]> {
  const offIn = off(ctx.global.features?.memories !== true)
  const warnings = [GENERATED_WARNING]
  const items: Item[] = []
  for (const root of [join(ctx.codexHome, "memories_v2"), join(ctx.codexHome, "memories")]) {
    if (!existsSync(root)) continue
    const entries = await readdir(root, { recursive: true, withFileTypes: true })
    for (const entry of entries.filter((e) => e.isFile())) {
      const path = join(entry.parentPath, entry.name)
      items.push(item({ kind: "memory", scope: "global", name: relative(root, path), path, offIn, warnings }))
    }
  }
  return items
}

function mcpItems(ctx: Context, scope: Scope): Item[] {
  const [table, path] = scope === "global" ? [ctx.global, ctx.globalPath] : [ctx.project, ctx.projectPath]
  const untrusted = scope === "project" && !ctx.trusted
  return Object.entries((table.mcp_servers ?? {}) as Table).map(([name, server]) =>
    item({
      kind: "mcp",
      scope,
      name,
      path,
      key: `mcp_servers.${name}`,
      offIn: off(untrusted || server.enabled === false),
      warnings: untrusted ? ["project not trusted in Codex"] : undefined,
    }),
  )
}

function toMcpServer(name: string, entry: Table): McpServer {
  const { command, args, env, url, http_headers, enabled, ...native } = entry
  const headers: Record<string, string> = { ...http_headers }
  if (native.bearer_token_env_var) headers.Authorization = `Bearer \${${native.bearer_token_env_var}}`
  const server: McpServer = { name, transport: url ? "http" : "stdio", enabled: enabled ?? true, native }
  if (command !== undefined) server.command = command
  if (args !== undefined) server.args = args
  if (env !== undefined) server.env = env
  if (url !== undefined) server.url = url
  if (Object.keys(headers).length > 0) server.headers = headers
  return server
}

// Last [[skills.config]] entry matching the skill's folder, SKILL.md or name decides.
function skillDisabled(ctx: Context, name: string, path: string): boolean {
  const entries: Table[] = Array.isArray(ctx.global.skills?.config) ? ctx.global.skills.config : []
  const matches = entries.filter((e) => e.name === name || e.path === path || e.path === join(path, "SKILL.md"))
  return matches.at(-1)?.enabled === false
}

async function skillsIn(ctx: Context, root: string, fields: Pick<Item, "scope" | "readOnly" | "warnings">): Promise<Item[]> {
  const folders = await listSkillFolders(root)
  return folders.map(({ name, path }) => item({ kind: "skill", name, path, offIn: off(skillDisabled(ctx, name, path)), ...fields }))
}

// Deepest project dir first.
const projectSkillRoots = (ctx: Context) => [...ctx.dirs].reverse().map((dir) => join(dir, ".agents", "skills"))

async function skills(ctx: Context, roots: Roots): Promise<Item[]> {
  const system = roots.env.CODEX_SYSTEM_SKILLS ?? "/etc/codex/skills"
  const projectRoots = projectSkillRoots(ctx)
  const lists = await Promise.all([
    skillsIn(ctx, join(ctx.home, ".agents", "skills"), { scope: "global" }),
    skillsIn(ctx, system, { scope: "global", readOnly: "system skills" }),
    skillsIn(ctx, join(ctx.codexHome, "skills"), { scope: "global", warnings: ["* likely not loaded: move to ~/.agents/skills"] }),
    ...projectRoots.map((root) => skillsIn(ctx, root, { scope: "project" })),
  ])
  return lists.flat()
}

async function subfolders(path: string): Promise<string[]> {
  if (!existsSync(path)) return []
  return (await readdir(path, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name)
}

// Installed plugins: plugins/cache/<marketplace>/<plugin>/<version>/, keyed by "<plugin>@<marketplace>".
async function installedPlugins(codexHome: string): Promise<Map<string, string>> {
  const installed = new Map<string, string>()
  const cache = join(codexHome, "plugins", "cache")
  for (const marketplace of await subfolders(cache)) {
    for (const plugin of await subfolders(join(cache, marketplace))) {
      const versions = (await subfolders(join(cache, marketplace, plugin))).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
      if (versions.length > 0) installed.set(`${plugin}@${marketplace}`, join(cache, marketplace, plugin, versions.at(-1)!))
    }
  }
  return installed
}

async function plugins(ctx: Context): Promise<Item[]> {
  const settings: Table = { ...ctx.global.plugins, ...(ctx.trusted ? ctx.project.plugins : {}) }
  const installed = await installedPlugins(ctx.codexHome)
  const names = [...new Set([...installed.keys(), ...Object.keys(settings)])]
  return names.map((name) => {
    const offIn = off(settings[name]?.enabled === false)
    const path = installed.get(name)
    if (path) return item({ kind: "plugin", scope: "global", name, path, offIn })
    return item({ kind: "plugin", scope: "global", name, path: ctx.globalPath, key: `plugins.${name}`, loadedBy: [], offIn, warnings: ["not installed"] })
  })
}

async function list(kind: Kind, roots: Roots): Promise<Item[]> {
  const ctx = context(roots)
  if (kind === "memory") return [...globalMemory(ctx), ...projectMemory(ctx), ...(await generatedMemory(ctx))]
  if (kind === "mcp") return [...mcpItems(ctx, "global"), ...mcpItems(ctx, "project")]
  if (kind === "skill") return skills(ctx, roots)
  return plugins(ctx)
}

async function read(target: Item): Promise<ItemDetail> {
  if (target.kind === "mcp") return { type: "mcp", server: toMcpServer(target.name, readToml(target.path).mcp_servers?.[target.name] ?? {}) }
  if (target.kind === "skill") return { type: "text", text: readFileSync(join(target.path, "SKILL.md"), "utf8") }
  if (target.kind === "memory") return { type: "text", text: readFileSync(target.path, "utf8") }
  const enabled = !target.offIn?.includes("codex")
  const source = target.name.split("@").at(-1)
  return { type: "plugin", plugin: target.key ? { name: target.name, enabled, source } : { name: target.name, enabled, version: basename(target.path), source } }
}

const ENV_REF = /^\$\{(\w+)\}$/
const BEARER_REF = /^Bearer \$\{(\w+)\}$/

// Splits headers into Codex's bearer_token_env_var, env_http_headers (exact ${VAR}) and literal http_headers.
function headerKeys(headers: Record<string, string>, native: Table): Table {
  const keys: Table = { bearer_token_env_var: undefined, http_headers: {}, env_http_headers: { ...native.env_http_headers } }
  for (const [header, value] of Object.entries(headers)) {
    const bearer = header === "Authorization" && BEARER_REF.exec(value)
    const ref = ENV_REF.exec(value)
    if (bearer) keys.bearer_token_env_var = bearer[1]
    else if (ref) keys.env_http_headers[header] = ref[1]
    else keys.http_headers[header] = value
  }
  return keys
}

// env values that are exactly ${KEY} become env_vars = ["KEY"]; the rest stay literal.
function envKeys(env: Record<string, string>, native: Table): Table {
  const keys: Table = { env: {}, env_vars: [...(native.env_vars ?? [])] }
  for (const [name, value] of Object.entries(env)) {
    if (value === `\${${name}}`) keys.env_vars.includes(name) || keys.env_vars.push(name)
    else keys.env[name] = value
  }
  return keys
}

const isEmpty = (value: unknown) => value === undefined || (typeof value === "object" && value !== null && Object.keys(value).length === 0)

function toCodexTable(server: McpServer): Table {
  if (server.transport === "sse") throw new Error("Codex: SSE MCP servers are not supported; use stdio or streamable HTTP")
  const { bearer_token_env_var: _bearer, env_vars: _envVars, env_http_headers: _envHeaders, ...native } = server.native
  const table: Table = {
    command: server.command,
    args: server.args,
    ...envKeys(server.env ?? {}, server.native),
    url: server.url,
    ...headerKeys(server.headers ?? {}, server.native),
    ...native,
    enabled: server.enabled ? undefined : false,
  }
  for (const key of Object.keys(table)) if (isEmpty(table[key])) delete table[key]
  return table
}

function patchServers(text: string, servers: Table): string {
  const doc = parse(text)
  if (Object.keys(servers).length > 0) doc.mcp_servers = servers
  else delete doc.mcp_servers
  return patch(text, doc)
}

// patch() writes a new sub-table inline at the root, so a new server is appended as its own section.
// shortcut: strips the [mcp_servers] header stringify adds; upgrade if toml-patch gains a section option.
function appendServer(text: string, server: McpServer): string {
  const section = stringify({ mcp_servers: { [server.name]: toCodexTable(server) } }, { inlineTableStart: 2 }).replace(/^\[mcp_servers\]\n\n/, "")
  return appendSection(text, section)
}

function appendSection(text: string, section: string): string {
  const separator = text === "" ? "" : text.endsWith("\n") ? "\n" : "\n\n"
  return text + separator + section
}

function editMcpServers(text: string, path: string, { op, item, server }: Change): string {
  const servers: Table = { ...parse(text).mcp_servers }
  if (op === "delete") {
    delete servers[item!.name]
    return patchServers(text, servers)
  }
  if ((op !== "create" && op !== "update") || !server) throw new Error(`Codex: MCP servers cannot ${op}`)
  if (op === "update" && item!.name === server.name) return patchServers(text, { ...servers, [server.name]: toCodexTable(server) })
  if (server.name in servers) throw new Error(`Codex: ${server.name} already exists in ${path}`)
  if (op === "create") return appendServer(text, server)
  delete servers[item!.name]
  return appendServer(patchServers(text, servers), server)
}

async function planMcp(change: Change, roots: Roots): Promise<WritePlan> {
  const { item } = change
  if (item?.readOnly) throw new Error(`Codex: ${item.name} is read-only (${item.readOnly})`)
  const ctx = context(roots)
  const path = item?.path ?? (change.target.scope === "global" ? ctx.globalPath : ctx.projectPath)
  const before = existsSync(path) ? readFileSync(path, "utf8") : null
  const after = editMcpServers(before ?? "", path, change)
  const notices = [SESSION_NOTICE]
  if (path === ctx.projectPath && !ctx.trusted) notices.push("Codex ignores this file until you trust the project.")
  return { ...emptyPlan(), edits: [{ path, before, after }], notices }
}

const SESSION_NOTICE = "Start a new Codex session to load this change."

// Plugin subcommands from the CLI source (openai/codex@57a808a):
// `codex plugin add|remove PLUGIN@MARKETPLACE`: https://github.com/openai/codex/blob/57a808a3920f05f2d4b9eab2d0493e1df136ae6b/codex-rs/cli/src/plugin_cmd.rs#L62-L81
// `codex plugin marketplace add SOURCE | remove MARKETPLACE_NAME`: https://github.com/openai/codex/blob/57a808a3920f05f2d4b9eab2d0493e1df136ae6b/codex-rs/cli/src/marketplace_cmd.rs#L43-L58
// There is no plugin upgrade or enable/disable subcommand; enable/disable edits [plugins."<name>"] in config.toml.
function pluginCommand(change: Change): string[] {
  const { op, item, plugin, marketplace } = change
  if (!plugin && !item && marketplace) return ["codex", "plugin", "marketplace", op === "create" ? "add" : "remove", marketplace]
  if (op === "create") return ["codex", "plugin", "add", plugin!.name]
  if (op === "delete") return ["codex", "plugin", "remove", item!.name]
  throw new Error(`Codex: plugin ${op} is not available from the command line; use the Codex app`)
}

function editPluginEnabled(text: string, name: string, enabled: boolean): string {
  const doc = parse(text) as Table
  if (!doc.plugins?.[name]) return appendSection(text, `[plugins.${JSON.stringify(name)}]\nenabled = ${enabled}\n`)
  doc.plugins[name].enabled = enabled
  return patch(text, doc)
}

async function planPlugin(change: Change, roots: Roots): Promise<WritePlan> {
  const { item, plugin } = change
  if (item?.readOnly) throw new Error(`Codex: ${item.name} is read-only (${item.readOnly})`)
  const ctx = context(roots)
  const notices = [SESSION_NOTICE]
  const toggles = change.op === "update" && item && plugin && plugin.enabled === Boolean(item.offIn?.includes("codex"))
  if (!toggles) return { ...emptyPlan(), commands: [{ argv: pluginCommand(change), touches: [ctx.globalPath], cwd: roots.project }], notices }
  const path = ctx.trusted && ctx.project.plugins?.[item.name] ? ctx.projectPath : ctx.globalPath
  const before = existsSync(path) ? readFileSync(path, "utf8") : null
  return { ...emptyPlan(), edits: [{ path, before, after: editPluginEnabled(before ?? "", item.name, plugin.enabled) }], notices }
}

// Marketplace files the Codex plugin docs name: personal, repo, and the legacy Claude-style location.
async function marketplaces(roots: Roots): Promise<{ name: string; source: string }[]> {
  const root = projectDirs(roots.project)[0]!
  const files = [join(roots.home, ".agents/plugins/marketplace.json"), join(root, ".agents/plugins/marketplace.json"), join(root, ".claude-plugin/marketplace.json")]
  return files.filter(existsSync).map((source) => {
    const data = JSON.parse(readFileSync(source, "utf8")) as Table
    return { name: typeof data.name === "string" ? data.name : basename(dirname(dirname(source))), source }
  })
}

async function plan(change: Change, roots: Roots): Promise<WritePlan> {
  if (change.kind === "mcp") return planMcp(change, roots)
  if (change.kind === "plugin") return planPlugin(change, roots)
  if (change.kind !== "memory") throw new Error(`Codex: ${change.kind} changes are not supported yet`)
  if (change.op === "update" && change.item?.warnings?.includes(GENERATED_WARNING)) throw new Error("Codex: generated memories can only be read or deleted")
  const scopeRoot = (scope: Scope) => (scope === "global" ? context(roots).codexHome : projectDirs(roots.project)[0]!)
  return planMemoryFile(change, { label: "Codex", scopeRoot, memoryFiles: MEMORY_FILES })
}

async function skillRoots(roots: Roots): Promise<{ path: string; scope: Scope }[]> {
  const ctx = context(roots)
  return [
    { path: join(ctx.home, ".agents", "skills"), scope: "global" },
    { path: join(ctx.codexHome, "skills"), scope: "global" },
    ...projectSkillRoots(ctx).map((path) => ({ path, scope: "project" as const })),
  ]
}

export const codex: HarnessAdapter = {
  id: "codex",
  label: "Codex",
  scopes: ["global", "project"],
  detect: async (roots) => existsSync(roots.env.CODEX_HOME ?? join(roots.home, ".codex")),
  list,
  read,
  plan,
  memoryFiles: MEMORY_FILES,
  skillRoots,
  marketplaces,
}
