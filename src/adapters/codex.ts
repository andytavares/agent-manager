import { existsSync, readFileSync } from "node:fs"
import { readdir } from "node:fs/promises"
import { basename, dirname, join, relative } from "node:path"
import { parse } from "@decimalturn/toml-patch"
import type { HarnessAdapter, Item, ItemDetail, Kind, McpServer, Roots, Scope } from "../core/model"
import { listSkillFolders } from "../core/skills"

type Table = Record<string, any>

interface Context {
  home: string
  codexHome: string
  globalPath: string
  global: Table
  dirs: string[] // project root down to roots.project
  projectPath: string
  project: Table
  trusted: boolean
}

// A missing or malformed file reads as an empty table, so it gives no items.
function readToml(path: string): Table {
  try {
    return existsSync(path) ? (parse(readFileSync(path, "utf8")) as Table) : {}
  } catch {
    return {}
  }
}

function projectDirs(project: string): string[] {
  const dirs: string[] = []
  for (let dir = project; ; dir = dirname(dir)) {
    dirs.unshift(dir)
    if (existsSync(join(dir, ".git"))) return dirs
    if (dirname(dir) === dir) return [project]
  }
}

function context(roots: Roots): Context {
  const codexHome = roots.env.CODEX_HOME ?? join(roots.home, ".codex")
  const globalPath = join(codexHome, "config.toml")
  const global = readToml(globalPath)
  const dirs = projectDirs(roots.project)
  const projectPath = join(dirs[0]!, ".codex", "config.toml")
  const trusted = global.projects?.[dirs[0]!]?.trust_level === "trusted"
  return { home: roots.home, codexHome, globalPath, global, dirs, projectPath, project: readToml(projectPath), trusted }
}

function item(fields: Omit<Item, "harness" | "loadedBy"> & { loadedBy?: Item["loadedBy"] }): Item {
  const loadedBy: Item["loadedBy"] = fields.offIn?.includes("codex") ? [] : ["codex"]
  const result: Item = { harness: "codex", loadedBy, ...fields }
  for (const key of ["offIn", "warnings", "readOnly"] as const) if (result[key] === undefined) delete result[key]
  return result
}

const off = (disabled: boolean) => (disabled ? (["codex"] as Item["offIn"]) : undefined)

function hasText(path: string): boolean {
  return existsSync(path) && readFileSync(path, "utf8").trim() !== ""
}

function globalMemory(ctx: Context): Item[] {
  const override = join(ctx.codexHome, "AGENTS.override.md")
  const agents = join(ctx.codexHome, "AGENTS.md")
  const overrideLoaded = hasText(override)
  const items: Item[] = []
  if (existsSync(override)) items.push(item({ kind: "memory", scope: "global", name: "AGENTS.override.md", path: override, loadedBy: overrideLoaded ? ["codex"] : [] }))
  if (existsSync(agents)) {
    const warnings = overrideLoaded ? ["shadowed by AGENTS.override.md"] : undefined
    items.push(item({ kind: "memory", scope: "global", name: "AGENTS.md", path: agents, loadedBy: overrideLoaded ? [] : ["codex"], warnings }))
  }
  return items
}

function projectMemory(ctx: Context): Item[] {
  const fallbacks: string[] = Array.isArray(ctx.global.project_doc_fallback_filenames) ? ctx.global.project_doc_fallback_filenames : []
  const names = ["AGENTS.override.md", "AGENTS.md", ...fallbacks]
  return ctx.dirs.flatMap((dir) => {
    const path = names.map((name) => join(dir, name)).find(hasText)
    return path ? [item({ kind: "memory", scope: "project", name: relative(ctx.dirs[0]!, path), path })] : []
  })
}

async function generatedMemory(ctx: Context): Promise<Item[]> {
  const offIn = off(ctx.global.features?.memories !== true)
  const warnings = ["generated by Codex: read and delete only"]
  const items: Item[] = []
  for (const root of [join(ctx.codexHome, "memories_v2"), join(ctx.codexHome, "memories")]) {
    if (!existsSync(root)) continue
    const entries = await readdir(root, { recursive: true, withFileTypes: true })
    for (const entry of entries.filter((e) => e.isFile())) {
      const path = join(entry.parentPath, entry.name)
      items.push(item({ kind: "memory", scope: "global", name: relative(root, path), path, offIn, warnings }))
    }
  }
  return items
}

function mcpItems(ctx: Context, scope: Scope): Item[] {
  const [table, path] = scope === "global" ? [ctx.global, ctx.globalPath] : [ctx.project, ctx.projectPath]
  const untrusted = scope === "project" && !ctx.trusted
  return Object.entries((table.mcp_servers ?? {}) as Table).map(([name, server]) =>
    item({
      kind: "mcp",
      scope,
      name,
      path,
      key: `mcp_servers.${name}`,
      offIn: off(untrusted || server.enabled === false),
      warnings: untrusted ? ["project not trusted in Codex"] : undefined,
    }),
  )
}

function toMcpServer(name: string, entry: Table): McpServer {
  const { command, args, env, url, http_headers, enabled, ...native } = entry
  const headers: Record<string, string> = { ...http_headers }
  if (native.bearer_token_env_var) headers.Authorization = `Bearer \${${native.bearer_token_env_var}}`
  const server: McpServer = { name, transport: url ? "http" : "stdio", enabled: enabled ?? true, native }
  if (command !== undefined) server.command = command
  if (args !== undefined) server.args = args
  if (env !== undefined) server.env = env
  if (url !== undefined) server.url = url
  if (Object.keys(headers).length > 0) server.headers = headers
  return server
}

// Last [[skills.config]] entry matching the skill's folder, SKILL.md or name decides.
function skillDisabled(ctx: Context, name: string, path: string): boolean {
  const entries: Table[] = Array.isArray(ctx.global.skills?.config) ? ctx.global.skills.config : []
  const matches = entries.filter((e) => e.name === name || e.path === path || e.path === join(path, "SKILL.md"))
  return matches.at(-1)?.enabled === false
}

async function skillsIn(ctx: Context, root: string, fields: Pick<Item, "scope" | "readOnly" | "warnings">): Promise<Item[]> {
  const folders = await listSkillFolders(root)
  return folders.map(({ name, path }) => item({ kind: "skill", name, path, offIn: off(skillDisabled(ctx, name, path)), ...fields }))
}

async function skills(ctx: Context, roots: Roots): Promise<Item[]> {
  const system = roots.env.CODEX_SYSTEM_SKILLS ?? "/etc/codex/skills"
  const projectRoots = [...ctx.dirs].reverse().map((dir) => join(dir, ".agents", "skills"))
  const lists = await Promise.all([
    skillsIn(ctx, join(ctx.home, ".agents", "skills"), { scope: "global" }),
    skillsIn(ctx, system, { scope: "global", readOnly: "system skills" }),
    skillsIn(ctx, join(ctx.codexHome, "skills"), { scope: "global", warnings: ["* likely not loaded: move to ~/.agents/skills"] }),
    ...projectRoots.map((root) => skillsIn(ctx, root, { scope: "project" })),
  ])
  return lists.flat()
}

async function subfolders(path: string): Promise<string[]> {
  if (!existsSync(path)) return []
  return (await readdir(path, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name)
}

// Installed plugins: plugins/cache/<marketplace>/<plugin>/<version>/, keyed by "<plugin>@<marketplace>".
async function installedPlugins(codexHome: string): Promise<Map<string, string>> {
  const installed = new Map<string, string>()
  const cache = join(codexHome, "plugins", "cache")
  for (const marketplace of await subfolders(cache)) {
    for (const plugin of await subfolders(join(cache, marketplace))) {
      const versions = (await subfolders(join(cache, marketplace, plugin))).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
      if (versions.length > 0) installed.set(`${plugin}@${marketplace}`, join(cache, marketplace, plugin, versions.at(-1)!))
    }
  }
  return installed
}

async function plugins(ctx: Context): Promise<Item[]> {
  const settings: Table = { ...ctx.global.plugins, ...(ctx.trusted ? ctx.project.plugins : {}) }
  const installed = await installedPlugins(ctx.codexHome)
  const names = [...new Set([...installed.keys(), ...Object.keys(settings)])]
  return names.map((name) => {
    const offIn = off(settings[name]?.enabled === false)
    const path = installed.get(name)
    if (path) return item({ kind: "plugin", scope: "global", name, path, offIn })
    return item({ kind: "plugin", scope: "global", name, path: ctx.globalPath, key: `plugins.${name}`, loadedBy: [], offIn, warnings: ["not installed"] })
  })
}

async function list(kind: Kind, roots: Roots): Promise<Item[]> {
  const ctx = context(roots)
  if (kind === "memory") return [...globalMemory(ctx), ...projectMemory(ctx), ...(await generatedMemory(ctx))]
  if (kind === "mcp") return [...mcpItems(ctx, "global"), ...mcpItems(ctx, "project")]
  if (kind === "skill") return skills(ctx, roots)
  return plugins(ctx)
}

async function read(target: Item): Promise<ItemDetail> {
  if (target.kind === "mcp") return { type: "mcp", server: toMcpServer(target.name, readToml(target.path).mcp_servers?.[target.name] ?? {}) }
  if (target.kind === "skill") return { type: "text", text: readFileSync(join(target.path, "SKILL.md"), "utf8") }
  if (target.kind === "memory") return { type: "text", text: readFileSync(target.path, "utf8") }
  const enabled = !target.offIn?.includes("codex")
  const source = target.name.split("@").at(-1)
  return { type: "plugin", plugin: target.key ? { name: target.name, enabled, source } : { name: target.name, enabled, version: basename(target.path), source } }
}

export const codex: HarnessAdapter = {
  id: "codex",
  label: "Codex",
  scopes: ["global", "project"],
  detect: async (roots) => existsSync(roots.env.CODEX_HOME ?? join(roots.home, ".codex")),
  list,
  read,
}
